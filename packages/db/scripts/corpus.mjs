// Turns the Markdown files in src/corpus/<workspace>/ into src/corpus/index.ts, so the seed can
// run anywhere (Node, the tests, the browser demo) without reading the disk. Run `pnpm corpus`
// after editing a document and commit both.
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const root = new URL("../src/corpus/", import.meta.url).pathname;
const entries = [];
for (const workspace of readdirSync(root, { withFileTypes: true }).filter((d) => d.isDirectory()).map((d) => d.name).sort()) {
  for (const file of readdirSync(join(root, workspace)).filter((f) => f.endsWith(".md")).sort()) {
    const body = readFileSync(join(root, workspace, file), "utf8");
    const title = body.split("\n")[0].replace(/^#\s*/, "").trim();
    entries.push({ workspace, slug: file.replace(/\.md$/, ""), title, body });
  }
}
const lines = [
  "// Generated by scripts/corpus.mjs from the Markdown files next to it. Do not edit by hand.",
  "",
  "export interface CorpusDocument {",
  "  workspace: string;",
  "  slug: string;",
  "  title: string;",
  "  body: string;",
  "}",
  "",
  "export const corpus: CorpusDocument[] = [",
  ...entries.map((e) => `  { workspace: ${JSON.stringify(e.workspace)}, slug: ${JSON.stringify(e.slug)}, title: ${JSON.stringify(e.title)}, body: ${JSON.stringify(e.body)} },`),
  "];",
  "",
];
writeFileSync(join(root, "index.ts"), lines.join("\n"));
console.log(`wrote ${entries.length} documents`);
