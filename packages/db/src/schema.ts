export const documents = pgTable(
  "documents",
  {
    id: text("id").primaryKey(),
    libraryId: text("library_id").notNull().references(() => libraries.id, { onDelete: "cascade" }),
    title: text("title").notNull(),
    sourceName: text("source_name").notNull(),
    mime: text("mime").notNull(),
    byteSize: integer("byte_size").notNull(),
    charCount: integer("char_count").notNull(),
    /** The text itself; chunks are spans of it and the viewer shows it whole. */
    body: text("body").notNull(),
    status: documentStatus("status").notNull(),
    error: text("error"),
    /** Replacing the text bumps the version; a citation remembers which one it quoted. */
    version: integer("version").notNull(),
    uploadedBy: text("uploaded_by").notNull().references(() => users.id),
    createdAt: at("created_at").notNull(),
    indexedAt: at("indexed_at"),
  },
  (t) => [
    check("documents_version_positive", sql`${t.version} >= 1`),
    check("documents_sizes_non_negative", sql`${t.byteSize} >= 0 and ${t.charCount} >= 0`),
    index("documents_library_idx").on(t.libraryId, t.status),
  ],
);

export const chunks = pgTable(
  "chunks",
  {
    id: text("id").primaryKey(),
    documentId: text("document_id").notNull().references(() => documents.id, { onDelete: "cascade" }),
    ordinal: integer("ordinal").notNull(),
    /** The Markdown headings above the chunk, outermost first. */
    headingPath: text("heading_path").array().notNull(),
    /** The same path joined with " > ", because the search vector must be generated from an immutable expression. */
    headingText: text("heading_text").notNull(),
    /** `document.body.slice(startChar, endChar)` is exactly `body`. */
    startChar: integer("start_char").notNull(),
    endChar: integer("end_char").notNull(),
    tokenCount: integer("token_count").notNull(),
    body: text("body").notNull(),
    tsv: tsvector("tsv").generatedAlwaysAs(
      sql`setweight(to_tsvector('english'::regconfig, heading_text), 'B') || setweight(to_tsvector('english'::regconfig, body), 'D')`,
    ),
  },
  (t) => [
    unique("chunks_document_ordinal_unique").on(t.documentId, t.ordinal),
    check("chunks_span_ordered", sql`${t.endChar} > ${t.startChar}`),
    check("chunks_tokens_positive", sql`${t.tokenCount} > 0`),
    index("chunks_tsv_idx").using("gin", t.tsv),
  ],
);

