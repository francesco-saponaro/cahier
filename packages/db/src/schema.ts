import { sql } from "drizzle-orm";
import {
  bigint,
  boolean,
  check,
  customType,
  index,
  integer,
  jsonb,
  pgEnum,
  pgTable,
  primaryKey,
  text,
  timestamp,
  unique,
  type AnyPgColumn,
} from "drizzle-orm/pg-core";

/*
 * The twenty-two tables of Cahier. Tokens are integers, money is bigint micro-dollars, prices are
 * integer micro-dollars per thousand tokens with a validity range, times are timestamptz, ids are
 * prefixed text so a log line says what it names (ws_, usr_, lib_, doc_, chk_, agt_, agv_, cnv_,
 * msg_, cit_ ...). Every state column is a PostgreSQL enum and every rule that can be a constraint
 * is one, so the database refuses what the use cases would refuse. The search vector on chunks is
 * generated by the database from the heading path and the body, and indexed with GIN.
 */

export const membershipRole = pgEnum("membership_role", ["member", "admin"]);
export const membershipStatus = pgEnum("membership_status", ["active", "suspended"]);
export const invitationStatus = pgEnum("invitation_status", ["sent", "accepted", "revoked", "expired"]);
export const priceKind = pgEnum("price_kind", ["input", "cached_input", "output"]);
export const visibility = pgEnum("visibility", ["private", "workspace"]);
export const documentStatus = pgEnum("document_status", ["uploaded", "processing", "indexed", "failed"]);
export const agentStatus = pgEnum("agent_status", ["active", "archived"]);
export const agentVersionStatus = pgEnum("agent_version_status", ["draft", "published", "retired"]);
export const shareSubjectKind = pgEnum("share_subject_kind", ["library", "agent"]);
export const shareStatus = pgEnum("share_status", ["requested", "approved", "declined", "withdrawn"]);
export const conversationStatus = pgEnum("conversation_status", ["active", "archived", "deleted"]);
export const messageRole = pgEnum("message_role", ["user", "assistant"]);
export const messageStatus = pgEnum("message_status", ["streaming", "complete", "failed", "refused"]);
export const refusedReason = pgEnum("refused_reason", ["budget_exhausted", "rate_limited", "tool_off", "no_sources", "no_price"]);
export const budgetStatus = pgEnum("budget_status", ["open", "closed"]);
export const cadence = pgEnum("cadence", ["once", "daily", "weekly", "monthly"]);
export const scheduleStatus = pgEnum("schedule_status", ["active", "paused", "ended"]);
export const runStatus = pgEnum("run_status", ["queued", "running", "succeeded", "failed", "skipped", "cancelled"]);

const at = (name: string) => timestamp(name, { withTimezone: true, mode: "date" });

const tsvector = customType<{ data: string }>({
  dataType() {
    return "tsvector";
  },
});

/** Which tools a workspace has switched on. */
export interface WorkspaceTools {
  groundedAnswers: boolean;
  scheduledPrompts: boolean;
  uploads: boolean;
}

export const workspaces = pgTable(
  "workspaces",
  {
    id: text("id").primaryKey(),
    slug: text("slug").notNull(),
    name: text("name").notNull(),
    tools: jsonb("tools").$type<WorkspaceTools>().notNull(),
    /** Archived conversations are deleted after this many days. */
    retentionDays: integer("retention_days").notNull(),
    createdAt: at("created_at").notNull(),
  },
  (t) => [unique("workspaces_slug_unique").on(t.slug), check("workspaces_retention_range", sql`${t.retentionDays} between 1 and 3650`)],
);

