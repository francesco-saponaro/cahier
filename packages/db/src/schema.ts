export const scheduledPrompts = pgTable(
  "scheduled_prompts",
  {
    id: text("id").primaryKey(),
    workspaceId: text("workspace_id").notNull().references(() => workspaces.id),
    userId: text("user_id").notNull().references(() => users.id),
    agentId: text("agent_id").notNull().references(() => agents.id),
    name: text("name").notNull(),
    prompt: text("prompt").notNull(),
    cadence: cadence("cadence").notNull(),
    /** Minutes after midnight in the schedule's time zone. */
    atMinute: integer("at_minute").notNull(),
    /** 0 = Sunday … 6 = Saturday, for weekly schedules. */
    weekday: integer("weekday"),
    /** 1 to 28, for monthly schedules, so every month has the day. */
    dayOfMonth: integer("day_of_month"),
    timezone: text("timezone").notNull(),
    nextRunAt: at("next_run_at"),
    status: scheduleStatus("status").notNull(),
    createdAt: at("created_at").notNull(),
    lastRunAt: at("last_run_at"),
  },
  (t) => [
    check("scheduled_prompts_minute_range", sql`${t.atMinute} between 0 and 1439`),
    check("scheduled_prompts_weekday_range", sql`${t.weekday} is null or ${t.weekday} between 0 and 6`),
    check("scheduled_prompts_day_range", sql`${t.dayOfMonth} is null or ${t.dayOfMonth} between 1 and 28`),
    check("scheduled_prompts_cadence_fields", sql`(${t.cadence} <> 'weekly' or ${t.weekday} is not null) and (${t.cadence} <> 'monthly' or ${t.dayOfMonth} is not null)`),
    index("scheduled_prompts_due_idx").on(t.status, t.nextRunAt),
  ],
);

